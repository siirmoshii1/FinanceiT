/**
 * Returns an inline SVG element string for the given icon key.
 */
export function getIcon(name, size = 20, className = '') {
  // Normalize key name (e.g., 'credit-card' -> 'creditCard', 'dollar-sign' -> 'dollarSign')
  const cleanName = name.replace(/-([a-z])/g, g => g[1].toUpperCase());
  const path = ICONS[cleanName] || ICONS[name] || ICONS.tag;
  return `<svg class="icon ${className}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${path}</svg>`;
}

// ================= THEME CONTROLLER =================

export function initTheme() {
  const savedTheme = localStorage.getItem('financeit_theme') || 'system';
  applyTheme(savedTheme);

  // Listen to OS theme changes if on system
  window.matchMedia('(prefers-color-scheme: dark)').addEventListener('change', () => {
    if (localStorage.getItem('financeit_theme') === 'system') {
      applyTheme('system');
    }
  });

  initFontSize();
}

// ================= FONT SIZE CONTROLLER =================

export function initFontSize() {
  const saved = localStorage.getItem('financeit_fontsize') || 'normal';
  applyFontSize(saved);
}

export function applyFontSize(size) {
  const valid = ['small', 'normal', 'large', 'xlarge'];
  const safe = valid.includes(size) ? size : 'normal';
  document.documentElement.setAttribute('data-font-size', safe);
  localStorage.setItem('financeit_fontsize', safe);

  document.querySelectorAll('.font-size-btn').forEach(btn => {
    if (btn.getAttribute('data-size') === safe) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });
}

export function applyTheme(theme) {
  const html = document.documentElement;
  const isDark = theme === 'dark' || (theme === 'system' && window.matchMedia('(prefers-color-scheme: dark)').matches);

  if (isDark) {
    html.setAttribute('data-theme', 'dark');
  } else {
    html.setAttribute('data-theme', 'light');
  }

  localStorage.setItem('financeit_theme', theme);
  updateThemeButton(theme);
}

export function toggleTheme() {
  const current = localStorage.getItem('financeit_theme') || 'system';
  let next = 'dark';
  if (current === 'dark') next = 'light';
  else if (current === 'light') next = 'dark';
  applyTheme(next);
}

function updateThemeButton(theme) {
  const btn = document.getElementById('theme-toggle-btn');
  if (btn) {
    const isDark = document.documentElement.getAttribute('data-theme') === 'dark';
    btn.innerHTML = getIcon(isDark ? 'sun' : 'moon', 18);
    btn.setAttribute('title', `Current: ${theme}. Click to switch theme.`);
    btn.setAttribute('aria-label', `Switch theme`);
  }
}

// ================= MODAL CONTROLLER =================

export function openModal(modalId) {
  const modal = document.getElementById(modalId);
  if (!modal) return;
  modal.classList.add('is-active');
  document.body.classList.add('modal-open');

  // Autofocus first input if exists
  const firstInput = modal.querySelector('input:not([type=hidden]), select');
  if (firstInput) {
    setTimeout(() => firstInput.focus(), 150);
  }
}

export function closeModal(modalId) {
  const modal = document.getElementById(modalId);
  if (!modal) return;
  modal.classList.remove('is-active');

  // Check if any other modal is open
  const anyOpen = document.querySelector('.modal.is-active');
  if (!anyOpen) {
    document.body.classList.remove('modal-open');
  }
}

// ================= TOAST CONTROLLER =================

export function showToast(message, type = 'info', duration = 3000) {
  let container = document.getElementById('toast-container');
  if (!container) {
    container = document.createElement('div');
    container.id = 'toast-container';
    container.className = 'toast-container';
    document.body.appendChild(container);
  }

  const toast = document.createElement('div');
  toast.className = `toast toast-${type}`;
  const iconKey = type === 'success' ? 'check' : (type === 'error' ? 'alertCircle' : 'info');
  toast.innerHTML = `
    <span class="toast-icon">${getIcon(iconKey, 16)}</span>
    <span class="toast-message">${escapeHtml(message)}</span>
  `;

  container.appendChild(toast);

  // Trigger enter animation
  requestAnimationFrame(() => {
    toast.classList.add('show');
  });

  setTimeout(() => {
    toast.classList.remove('show');
    toast.addEventListener('transitionend', () => toast.remove());
  }, duration);
}

// ================= ESCAPE HTML =================

export function escapeHtml(str) {
  if (str === null || str === undefined) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
